"""Decision-focused business analysis of ULB fraud transactions (historical, observational).

Run from the project root:
    python -m src.business_analysis
    python -m src.business_analysis --input data/processed/deduped.csv --output reports/tables/business/dedup

Requires the validated, *unscaled* CSV generated by src.data_cleaner.
Do NOT interpret recorded fraudulent transaction value as realized loss or savings.
Segment-review scenarios are IN-SAMPLE retrospective thought experiments, NOT
validated fraud-detection rules, deployment recommendations, or model results.

Outputs: executive_kpis.csv, amount_segment_exposure.csv, time_segment_exposure.csv,
zero_amount_exposure.csv, value_concentration.csv, review_policy_scenarios.csv,
assumption_sensitivity.csv, executive_summary.md, methodology.json.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

try:
    from .data_cleaner import PROJECT_ROOT, PROCESSED_PATH, validate_data
except ImportError:
    from data_cleaner import PROJECT_ROOT, PROCESSED_PATH, validate_data

DEFAULT_OUTPUT = PROJECT_ROOT / 'reports' / 'tables' / 'business'
TARGET = 'Class'
AMOUNT = 'Amount'
TIME = 'Time'


def load_validated(path: str | Path) -> pd.DataFrame:
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f'Missing {path}; run python -m src.data_cleaner first')
    df = pd.read_csv(path, low_memory=False)
    if df.empty:
        raise ValueError('Input dataset is empty')
    validate_data(df)
    if df[AMOUNT].lt(0).any() or df[TIME].lt(0).any():
        raise ValueError('Negative Amount or Time is not supported')
    if not (df[TARGET].eq(0).any() and df[TARGET].eq(1).any()):
        raise ValueError('Both target classes must be present for this analysis')
    return df


def _fraud_amount(df: pd.DataFrame) -> pd.Series:
    return df[AMOUNT].where(df[TARGET].eq(1), 0.0)


def _summary(df: pd.DataFrame) -> dict[str, float | int]:
    n = len(df)
    fraud = df[TARGET].eq(1)
    fraud_value = float(df.loc[fraud, AMOUNT].sum())
    total_value = float(df[AMOUNT].sum())
    return dict(
        transactions=n, fraud_cases=int(fraud.sum()), legitimate_cases=int((~fraud).sum()),
        fraud_rate_pct=100 * float(fraud.mean()),
        total_recorded_value=total_value,
        recorded_fraud_value=fraud_value,
        fraud_value_share_pct=100 * fraud_value / total_value if total_value > 0 else 0.0,
        mean_fraud_amount=float(df.loc[fraud, AMOUNT].mean()),
        median_fraud_amount=float(df.loc[fraud, AMOUNT].median()),
        duplicate_rows=int(df.duplicated().sum()),
        span_hours=float((df[TIME].max()-df[TIME].min())/3600),
    )


def amount_bands(df: pd.DataFrame, quantiles: int = 10) -> pd.Series:
    if not (2 <= quantiles <= 100):
        raise ValueError('quantiles must be within 2..100')
    bands = pd.qcut(df[AMOUNT], q=quantiles, labels=False, duplicates='drop')
    if bands.isna().any() or bands.nunique() < 2:
        raise ValueError('Insufficient unique transaction amounts for quantile analysis')
    return bands.astype(int)


def _aggregate(df: pd.DataFrame, labels: pd.Series, name: str) -> pd.DataFrame:
    working = pd.DataFrame({name: labels.to_numpy(), 'fraud': df[TARGET].to_numpy(),
                            'amount': df[AMOUNT].to_numpy(),
                            'fraud_amount': _fraud_amount(df).to_numpy()})
    out = (working.groupby(name, observed=True, sort=True)
           .agg(transactions=('fraud', 'size'), fraud_cases=('fraud', 'sum'),
                total_amount=('amount', 'sum'), fraud_amount=('fraud_amount', 'sum'),
                min_amount=('amount', 'min'), max_amount=('amount', 'max'))
           .reset_index())
    totals = _summary(df)
    out['legitimate_cases'] = out['transactions'] - out['fraud_cases']
    out['fraud_rate_pct'] = 100 * out['fraud_cases'] / out['transactions']
    out['share_of_fraud_cases_pct'] = 100 * out['fraud_cases'] / totals['fraud_cases']
    out['share_of_fraud_value_pct'] = 100 * out['fraud_amount'] / totals['recorded_fraud_value']
    out['fraud_value_per_1000_transactions'] = 1000 * out['fraud_amount'] / out['transactions']
    out['fraud_cases_per_1000_transactions'] = 1000 * out['fraud_cases'] / out['transactions']
    out['fraud_value_share_of_segment_pct'] = np.where(
        out['total_amount'] > 0, 100 * out['fraud_amount'] / out['total_amount'], np.nan)
    return out


def amount_exposure(df: pd.DataFrame, quantiles: int = 10) -> pd.DataFrame:
    bands = amount_bands(df, quantiles)
    result = _aggregate(df, bands, 'amount_band')
    result['median_amount'] = df.groupby(bands, observed=True)[AMOUNT].median().to_numpy()
    return result


def time_exposure(df: pd.DataFrame, interval_hours: float = 4.0) -> pd.DataFrame:
    if not np.isfinite(interval_hours) or interval_hours <= 0:
        raise ValueError('interval_hours must be positive and finite')
    # Time is elapsed seconds, not a known clock hour. Anchor at Time=0.
    interval_sec = interval_hours * 3600
    segment = pd.Series(np.floor(df[TIME].to_numpy() / interval_sec).astype(int), index=df.index)
    out = _aggregate(df, segment, 'time_segment')
    out['elapsed_start_hours'] = out['time_segment'] * interval_hours
    out['elapsed_end_hours'] = (out['time_segment'] + 1) * interval_hours
    return out.drop(columns=['min_amount', 'max_amount'])


def zero_amount_exposure(df: pd.DataFrame) -> pd.DataFrame:
    labels = pd.Series(np.where(df[AMOUNT].eq(0), 'zero', 'positive'), index=df.index)
    return _aggregate(df, labels, 'amount_type')


def value_concentration(amount_table: pd.DataFrame) -> pd.DataFrame:
    result = amount_table[['amount_band','transactions','fraud_cases','fraud_amount',
                           'share_of_fraud_value_pct']].copy()
    result['cumulative_fraud_value_pct'] = result['share_of_fraud_value_pct'].cumsum()
    return result


def review_policy_masks(df: pd.DataFrame, bands: pd.Series) -> dict[str, pd.Series]:
    """Illustrative eligibility flags only; never a deployed risk rule."""
    low, high = int(bands.min()), int(bands.max())
    low_mask = bands.eq(low)
    high_mask = bands.eq(high)
    zero_mask = df[AMOUNT].eq(0)
    return {
        'review_all': pd.Series(True, index=df.index),
        'review_zero_amount': zero_mask,
        'review_lowest_amount_band': low_mask,
        'review_highest_amount_band': high_mask,
        'review_lowest_or_highest_band': low_mask | high_mask,
    }


def review_policy_table(df: pd.DataFrame, bands: pd.Series) -> pd.DataFrame:
    """Actual in-sample prevalence/yield under broad eligibility rules.

    A review flag is not a classifier prediction. Here a 'hit' means a flagged
    transaction whose ground-truth label is fraud (an oracle review outcome).
    """
    n = len(df)
    fraud = df[TARGET].eq(1)
    total_fraud = int(fraud.sum())
    total_fraud_value = float(df.loc[fraud, AMOUNT].sum())
    rows = []
    for name, mask in review_policy_masks(df, bands).items():
        flagged = int(mask.sum())
        caught = int((fraud & mask).sum())
        false_alert = flagged - caught
        caught_value = float(df.loc[fraud & mask, AMOUNT].sum())
        rows.append({
            'policy': name, 'flagged_for_review': flagged,
            'review_share_pct': 100 * flagged / n,
            'reviews_per_1000_transactions': 1000 * flagged / n,
            'labeled_fraud_in_flagged': caught,
            'legitimate_in_flagged': false_alert,
            'observed_review_yield_pct': 100 * caught / flagged if flagged else np.nan,
            'case_coverage_pct': 100 * caught / total_fraud,
            'flagged_fraud_value': caught_value,
            'value_coverage_pct': 100 * caught_value / total_fraud_value if total_fraud_value else np.nan,
            'unflagged_fraud_value': total_fraud_value - caught_value,
            'flagged_fraud_cases_missed': total_fraud - caught,
        })
    return pd.DataFrame(rows)


def assumption_scenarios(policy_table: pd.DataFrame, review_costs: tuple[float, ...] = (1, 5, 10),
                         recoveries: tuple[float, ...] = (.25, .5, 1.0),
                         false_positive_friction_cost: float = 0.0) -> pd.DataFrame:
    """Illustrative incremental benefit vs doing nothing, not realized savings.

    Hypotheses: every flagged transaction is reviewed, the review outcome is
    perfect (oracle), every flagged fraudulent amount is preventable with the
    assumed effectiveness, and each review incurs a flat cost. No account/customer
    dependence, transfer delays, downstream harm, or investigation capacity model.
    """
    values = tuple(review_costs) + tuple(recoveries) + (false_positive_friction_cost,)
    if not all(np.isfinite(v) for v in values) or any(v < 0 for v in values):
        raise ValueError('Scenario assumptions must be finite and nonnegative')
    if any(r > 1 for r in recoveries):
        raise ValueError('Recovery fractions must be <= 1')
    records = []
    for r in policy_table.itertuples(index=False):
        for review_cost in review_costs:
            for recovery in recoveries:
                gross = float(r.flagged_fraud_value) * recovery
                review_total = float(r.flagged_for_review) * review_cost
                friction = float(r.legitimate_in_flagged) * false_positive_friction_cost
                records.append({
                    'policy': r.policy, 'assumed_cost_per_review': review_cost,
                    'assumed_fraud_intervention_effectiveness': recovery,
                    'assumed_friction_cost_per_legitimate_review': false_positive_friction_cost,
                    'flagged_for_review': r.flagged_for_review,
                    'gross_hypothetical_value_prevented': gross,
                    'total_review_cost': review_total,
                    'total_false_positive_friction_cost': friction,
                    'hypothetical_incremental_net_value': gross - review_total - friction,
                })
    return pd.DataFrame(records)


def _check_reconciliation(df: pd.DataFrame, amount: pd.DataFrame,
                          time: pd.DataFrame, zero: pd.DataFrame, policies: pd.DataFrame):
    fraud_value = float(_fraud_amount(df).sum())
    for label, table in [('amount', amount), ('time', time), ('zero', zero)]:
        if int(table['transactions'].sum()) != len(df):
            raise AssertionError(f'{label}: transaction totals do not reconcile')
        if int(table['fraud_cases'].sum()) != int(df[TARGET].sum()):
            raise AssertionError(f'{label}: fraud counts do not reconcile')
        if not np.isclose(float(table['fraud_amount'].sum()), fraud_value, rtol=0, atol=0.01):
            raise AssertionError(f'{label}: fraud amounts do not reconcile')
    row = policies.set_index('policy').loc['review_all']
    if int(row.flagged_for_review) != len(df) or not np.isclose(row.flagged_fraud_value, fraud_value, atol=.01):
        raise AssertionError('review_all policy does not reconcile')


def _write_summary(summary: dict[str, float | int], amount: pd.DataFrame,
                   zero: pd.DataFrame, policies: pd.DataFrame, output: Path,
                   provenance: dict[str, Any]) -> None:
    low = amount.iloc[0]; high = amount.iloc[-1]
    z = zero.set_index('amount_type')
    lines = [
        '# Credit Card Fraud — Business Decision Brief', '',
        '## Observed facts (historical dataset)', '',
        f"- **{summary['transactions']:,}** transactions; **{summary['fraud_cases']:,}** labeled frauds "
        f"(**{summary['fraud_rate_pct']:.4f}%** of transactions).",
        f"- Recorded fraudulent transaction amount: **{summary['recorded_fraud_value']:,.2f} source units** "
        f"(**{summary['fraud_value_share_pct']:.4f}%** of total recorded transaction amount).",
        f"- Lowest amount quantile: **{int(low.fraud_cases)}** fraud cases "
        f"(**{low.share_of_fraud_cases_pct:.2f}%** of fraud cases); "
        f"recorded fraudulent amount **{low.fraud_amount:,.2f}**.",
        f"- Highest amount quantile: **{int(high.fraud_cases)}** fraud cases, "
        f"but **{high.share_of_fraud_value_pct:.2f}%** of total fraudulent amount.",
        f"- Zero-amount group: **{int(z.loc['zero','fraud_cases'])}** fraud cases "
        f"among **{int(z.loc['zero','transactions']):,}** records; this is an association, not evidence of card testing.",
        '', '## Decision implications', '',
        '- Compare **case coverage** and **fraud-value coverage** as distinct objectives.',
        '- Review workload must be considered before selecting a policy; amount bands alone are broad and expensive to investigate.',
        '- Zero-amount cases warrant investigation of transaction semantics, not an automatic blocking rule.',
        '', '## Scenario limitations', '',
        '- Policy rows reflect **in-sample, label-informed retrospective counts**, not model generalization or a validated decision rule.',
        '- The hypothetical net-value scenarios assume perfect reviews and a specified intervention-effectiveness fraction.',
        '- Recorded fraudulent amount is **not observed financial loss, recoverable loss, or realized savings**.',
        '- No customer IDs, merchant IDs, timestamp origin, or downstream intervention outcomes are available.',
        '- Transaction dependence, duplicates, temporal drift, and changes in future behavior are unresolved.',
        '- Currency is kept as **source units**; validate the original dataset documentation before interpreting as EUR.',
        '', '## Provenance', '',
        f"- Input: `{provenance['input_path']}`",
        f"- SHA-256: `{provenance['sha256']}`",
        f"- Created UTC: `{provenance['created_utc']}`",
        '', '## Next required validation', '',
        'Re-run the current ML pipeline with train-only preprocessing and a held-out chronological test. '
        'Evaluate alerts, case coverage, value coverage, and assumed cost on actual out-of-sample predictions.',
    ]
    (output / 'executive_summary.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def run(input_path: str | Path = PROCESSED_PATH, output: str | Path = DEFAULT_OUTPUT,
        quantiles: int = 10, interval_hours: float = 4,
        review_costs: tuple[float, ...] = (1, 5, 10),
        recoveries: tuple[float, ...] = (.25, .5, 1.0),
        friction: float = 0.0) -> dict[str, pd.DataFrame]:
    input_path = Path(input_path).resolve()
    output = Path(output).resolve()
    df = load_validated(input_path)
    overview = _summary(df)
    amount = amount_exposure(df, quantiles)
    times = time_exposure(df, interval_hours)
    zero = zero_amount_exposure(df)
    concentration = value_concentration(amount)
    policies = review_policy_table(df, amount_bands(df, quantiles))
    sensitivity = assumption_scenarios(policies, review_costs, recoveries, friction)
    _check_reconciliation(df, amount, times, zero, policies)
    output.mkdir(parents=True, exist_ok=True)
    overview_df = pd.DataFrame([overview])
    tables = {
        'executive_kpis': overview_df,
        'amount_segment_exposure': amount,
        'time_segment_exposure': times,
        'zero_amount_exposure': zero,
        'value_concentration': concentration,
        'review_policy_scenarios': policies,
        'assumption_sensitivity': sensitivity,
    }
    for name, table in tables.items():
        table.to_csv(output / f'{name}.csv', index=False, float_format='%.8f')
    h = hashlib.sha256()
    with input_path.open('rb') as f:
        for chunk in iter(lambda: f.read(4 * 1024 * 1024), b''):
            h.update(chunk)
    provenance = {
        'input_path': str(input_path), 'sha256': h.hexdigest(),
        'created_utc': datetime.now(timezone.utc).isoformat(),
        'output_path': str(output), 'quantile_count_requested': quantiles,
        'quantile_count_actual': len(amount), 'time_interval_hours': interval_hours,
        'source_currency': 'unverified (original Amount units)',
        'assumed_review_costs_source_units': list(review_costs),
        'assumed_intervention_effectiveness': list(recoveries),
        'assumed_friction_cost_per_legitimate_review': friction,
        'fraud_value_definition': 'sum(Amount where Class == 1), not booked losses',
        'data_policy': 'No rows altered, duplicate removal optional upstream',
        'policy_note': 'In-sample descriptive review scenarios, not out-of-sample predictions',
        'scenario_note': 'Perfect oracle review and assumed intervention effectiveness; illustrative only',
    }
    (output / 'methodology.json').write_text(json.dumps(provenance, indent=2), encoding='utf-8')
    _write_summary(overview, amount, zero, policies, output, provenance)
    print(f"[business] {overview['transactions']:,} records; {overview['fraud_cases']} frauds "
          f"({overview['fraud_rate_pct']:.4f}%); fraud value {overview['recorded_fraud_value']:,.2f} source units")
    print(f"[business] Lowest band: {int(amount.iloc[0].fraud_cases)} cases; "
          f"highest band: {amount.iloc[-1].share_of_fraud_value_pct:.2f}% of fraud value")
    print('[business] Retrospective review workloads (NOT operational model results):')
    print(policies[['policy', 'flagged_for_review', 'observed_review_yield_pct',
                    'case_coverage_pct', 'value_coverage_pct']].round(3).to_string(index=False))
    print(f'[business] Saved {len(tables)} CSV tables, executive_summary.md and methodology.json to {output}')
    return tables


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('--input', default=str(PROCESSED_PATH))
    p.add_argument('--output', default=str(DEFAULT_OUTPUT))
    p.add_argument('--quantiles', type=int, default=10)
    p.add_argument('--time-hours', type=float, default=4.0)
    p.add_argument('--review-costs', type=float, nargs='+', default=[1.0, 5.0, 10.0])
    p.add_argument('--recovery-rates', type=float, nargs='+', default=[.25, .5, 1.0])
    p.add_argument('--friction-cost', type=float, default=0.0)
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> None:
    args = parse_args(argv)
    run(args.input, args.output, args.quantiles, args.time_hours,
        tuple(args.review_costs), tuple(args.recovery_rates), args.friction_cost)


if __name__ == '__main__':
    main()
